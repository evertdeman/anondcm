"""Regenerate ``src/anondcm/_ps315.py`` from the published DICOM standard.

The DICOM PS3.15 Annex E confidentiality table is taken from the
innolitics/dicom-standard project (a machine-readable form of the standard),
so the rules are auditable and reproducible rather than hand-transcribed.

Usage (from the repo root)::

    uv run python scripts/generate_ps315.py

Action mapping from the Basic Profile column:
  * ``X`` -> REMOVE, ``Z``/``D`` and combinations -> BLANK.
  * Sequences -> REMOVE (a sequence cannot be given a zero-length value).
  * ``U`` and all UID-valued attributes -> left to ``Configuration.consistent_uids``.
  * A small set of key identifiers -> HASH, to keep related studies linkable
    (a deliberate, documented deviation from the Basic Profile, which blanks them).
"""

from __future__ import annotations

import json
import urllib.request
from collections import Counter
from pathlib import Path

SOURCE_URL = (
    "https://raw.githubusercontent.com/innolitics/dicom-standard/master/"
    "standard/confidentiality_profile_attributes.json"
)
OUTPUT = Path(__file__).resolve().parent.parent / "src" / "anondcm" / "_ps315.py"

HASH_KEYWORDS = {
    "PatientID",
    "PatientName",
    "OtherPatientIDs",
    "OtherPatientNames",
    "AccessionNumber",
    "StudyID",
}


def build_rules() -> dict[str, str]:
    from pydicom.datadict import dictionary_VR, keyword_for_tag

    with urllib.request.urlopen(SOURCE_URL) as response:  # noqa: S310 (trusted URL)
        data = json.load(response)

    rules: dict[str, str] = {}
    for entry in data:
        ident = entry["id"]
        if "x" in ident.lower():
            continue  # repeating-group tag (overlays/curves)
        try:
            tag = int(ident, 16)
        except ValueError:
            continue  # special rows such as the private-attributes catch-all
        keyword = keyword_for_tag(tag)
        if not keyword:
            continue
        try:
            vr = dictionary_VR(tag)
        except KeyError:
            vr = ""

        action_code = entry["basicProfile"]
        if vr == "UI" or action_code == "U":
            continue  # handled by Configuration.consistent_uids

        if keyword in HASH_KEYWORDS:
            rules[keyword] = "HASH"
        elif vr == "SQ":
            rules[keyword] = "REMOVE"
        elif "Z" in action_code or action_code == "D":
            rules[keyword] = "BLANK"
        elif "X" in action_code:
            rules[keyword] = "REMOVE"
    return rules


def render(rules: dict[str, str]) -> str:
    lines = [
        '"""DICOM PS3.15 Basic Confidentiality Profile rules.',
        "",
        "Generated by scripts/generate_ps315.py from the innolitics/dicom-standard",
        "confidentiality profile table. Do not edit by hand.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from anondcm.configuration import Action, RuleLike",
        "",
        "PS315_RULES: dict[str, RuleLike] = {",
        *(f'    "{kw}": Action.{rules[kw]},' for kw in sorted(rules)),
        "}",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    rules = build_rules()
    OUTPUT.write_text(render(rules))
    print(f"wrote {len(rules)} rules to {OUTPUT}")
    print("distribution:", dict(Counter(rules.values())))


if __name__ == "__main__":
    main()
